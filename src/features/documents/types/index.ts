import { z } from 'zod';
import { Party } from "@/features/parties/types";
import { Product } from "@/features/products/types";

export const DocumentTypeEnum = z.enum(['INVOICE', 'CREDIT_NOTE', 'DEBIT_NOTE', 'PAYROLL', 'PAYROLL_ADJUST', 'DOC_SUPPORT', 'RECEIPT', 'QUOTATION', 'SALES_ORDER', 'DELIVERY_NOTE', 'PURCHASE_ORDER', 'VENDOR_BILL']);
export const DocumentStatusEnum = z.enum(['DRAFT', 'SIGNED', 'SENT', 'ACCEPTED', 'REJECTED', 'VOIDED']);

export type DocumentType = z.infer<typeof DocumentTypeEnum>;
export type DocumentStatus = z.infer<typeof DocumentStatusEnum>;

// Line Item Schema
export const documentLineSchema = z.object({
    id: z.string().optional(),
    document_id: z.string().optional(),
    product_id: z.string().uuid().optional().nullable(),
    warehouse_id: z.string().uuid().optional().nullable(),
    lot_id: z.string().uuid().optional().nullable(),
    description: z.string().optional().default(''),
    qty: z.coerce.number().min(0).default(1),
    unit_price: z.coerce.number().min(0).default(0),
    line_total: z.coerce.number().min(0).default(0),
    tax_config: z.any().optional().nullable(),
});

export type DocumentLine = z.infer<typeof documentLineSchema>;

// Electronic Document Schema (DIAN)
export const electronicDocumentSchema = z.object({
    id: z.string().uuid().optional(),
    document_id: z.string().uuid(),
    environment: z.string(),
    cufe: z.string().optional(),
    xml_url: z.string().optional(),
    qr_data: z.string().optional(),
    dian_status: z.string(),
    rejection_reasons: z.string().optional(),
    sent_at: z.string().optional(),
});

export type ElectronicDocument = z.infer<typeof electronicDocumentSchema>;

// Header Schema
export const documentSchema = z.object({
    id: z.string().uuid().optional(),
    tenant_id: z.string().uuid().optional(),

    doc_type: DocumentTypeEnum,
    number: z.string().optional(), // Generated by backend

    party_id: z.string().min(1, "Debes seleccionar un cliente/tercero"),
    warehouse_id: z.string().uuid().optional().nullable(),

    issue_date: z.string().refine((val) => !isNaN(Date.parse(val)), "Fecha inválida"),
    due_date: z.string().optional().nullable(),
    expected_delivery_date: z.string().optional().nullable(),

    currency: z.string().default('COP'),

    // Contado/crédito: define qué asiento contable arma el motor de ventas.
    // Vacío = se deduce del plazo de pago del tercero.
    payment_form: z.preprocess(
        (v) => (v === '' ? null : v),
        z.enum(['CONTADO', 'CREDITO']).nullable().optional(),
    ),

    subtotal: z.number().default(0),
    taxes: z.number().default(0),
    total: z.number().default(0),
    balance: z.number().default(0).optional(),

    status: DocumentStatusEnum.default('DRAFT'),

    parent_id: z.string().uuid().optional().nullable(),
    notes_internal: z.string().optional().nullable(),
    notes_public: z.string().optional().nullable(),

    // Facturas (FEV) asociadas a un pedido marcado como facturado. Un pedido
    // puede corresponder a varias facturas.
    invoice_numbers: z.array(z.string()).optional().nullable(),

    // Observaciones finales: se registran cuando el documento ya está cerrado
    // (pedido facturado). Se imprimen al final del PDF del pedido.
    final_notes: z.string().optional().nullable(),
    final_notes_at: z.string().optional().nullable(),
    final_notes_by: z.string().uuid().optional().nullable(),

    // ICA Compliance (Resolución 1056) — receta médica + comercial responsable
    prescription_url: z.string().optional().nullable(),
    prescription_doctor_name: z.string().optional().nullable(),
    prescription_doctor_license: z.string().optional().nullable(),
    prescription_doctor_type: z.enum(['VETERINARIO', 'ZOOTECNISTA']).optional().nullable(),
    prescription_date: z.string().optional().nullable(),
    commercial_user_id: z.string().uuid().optional().nullable(),

    created_at: z.string().optional(),

    // Clave de idempotencia: la genera el formulario, una por intento de guardado.
    // El índice único (tenant_id, idempotency_key) impide que un doble clic, un
    // reintento tras error de red o un envío desde otra pestaña creen dos
    // documentos con dos consecutivos distintos.
    idempotency_key: z.string().uuid().optional().nullable(),

    // Relations (optional for fetching)
    party: z.custom<Party>().optional(),
    warehouse: z.object({ id: z.string(), name: z.string(), code: z.string().optional().nullable() }).optional().nullable(),
    lines: z.array(documentLineSchema).optional(),
    electronic_document: electronicDocumentSchema.optional().nullable(),
}).superRefine((data, ctx) => {
    // OJO: esta regla corre en CREATE y en EDIT por igual (el schema no sabe
    // distinguirlos). Por eso aquí solo va la regla del IVA, que es segura en
    // ambos casos (verificado: las 970 líneas de texto libre que ya existen en
    // producción tienen tax_config con una tarifa, nunca vacío). La regla de
    // "producto de catálogo obligatorio" para Factura/Nota Crédito SÍ hubiera
    // bloqueado editar 3 facturas reales con 14 líneas de texto libre viejas —
    // por eso vive aparte, en missingCatalogProductLines(), y solo se aplica al
    // CREAR un documento nuevo (ver createSalesDocumentAction/DocumentForm).
    (data.lines ?? []).forEach((line, i) => {
        // Para líneas SIN producto (pedidos, cotizaciones, remisiones): antes el
        // IVA quedaba en 0% por defecto sin que nadie lo eligiera a propósito —
        // Andrés detectó que eso venía afectando la contabilización. Ahora hay
        // que elegirlo explícitamente.
        if (!line.product_id) {
            const rate = Array.isArray(line.tax_config) && line.tax_config.length > 0
                ? line.tax_config[0]?.rate
                : undefined;
            if (rate === undefined || rate === null || rate === '') {
                ctx.addIssue({
                    code: z.ZodIssueCode.custom,
                    message: 'Selecciona el IVA de esta línea (no tiene producto del catálogo que lo determine).',
                    path: ['lines', i, 'tax_config'],
                });
            }
        }
    });
});

export type Document = z.infer<typeof documentSchema>;

// Reunión con Andrés (contador), 2026-09-29: en Factura y Nota Crédito — los
// ÚNICOS doc_type que hoy contabiliza salesAccountingEngine — solo se permiten
// productos reales del catálogo (nunca texto libre), porque una línea sin
// producto real es una línea sin cuenta de ingreso identificable.
//
// A propósito NO vive en el .superRefine() de arriba: ese corre también al
// EDITAR, y 3 facturas reales ya tienen 14 líneas de texto libre de antes de
// esta regla — aplicarla ahí las habría dejado imposibles de guardar. Los
// llamadores deben invocar esto SOLO al crear un documento nuevo.
export const CATALOG_REQUIRED_DOC_TYPES: DocumentType[] = ['INVOICE', 'CREDIT_NOTE'];

export function missingCatalogProductLines(doc: Pick<Document, 'doc_type' | 'lines'>): number[] {
    if (!CATALOG_REQUIRED_DOC_TYPES.includes(doc.doc_type)) return [];
    return (doc.lines ?? [])
        .map((line, i) => (line.product_id ? -1 : i))
        .filter((i) => i >= 0);
}

